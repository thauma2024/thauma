print( "&", "0b100&0b110", bin(0b100&0b110) ) #按位与运算
print( '|', '0b100/0b110', bin(0b100|0b110) ) #或
print( "^", '0b100^0b110', bin(0b100^0b110) ) #异或
print( "\n~", '~0b100', bin(~0b100) , '~0b110', bin(~0b110) ) #取反
print( '\n>>', '0b1000>>2', bin(0b1000>>2) )
print( '<<', '0b1000<<2', bin(0b1000<<2) )
