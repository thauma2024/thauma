#多行字符串，用三个' or " 装
info1 = '''
小白吃阿飞与巴迪
我吃卫龙辣条
'''
print(info1)

#\n
print( "牛油小串\n真好吃啊")

#\t （一个制表符是8个字符串）
print( "hellooooooooo")
print( "hellooo\tooooo")

#\'单引号 \"双引号 \\反斜杠
print( "hamilton is \'nonstop\'" )
print( "hamilton is \"nonstop\"" )
print( "在C语言里用\\\\作为注释的标识" )

#r or R 转义字符
print( "I\nlove\nu")
print(r"I\nlove\nu" ) #I\nlove\nu
print(R"I\nlove\nu" )